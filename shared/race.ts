export type Flag = "green" | "yellow" | "red";
export type RunStatus = "queued" | "onstage" | "finished" | "dnf";

export interface Penalty {
  ruleId: string;
  name: string;
  ms: number;
}

export interface Run {
  id: string;
  name: string;
  plate: string;
  status: RunStatus;
  /** Server time (ms) the timer starts. In the future during the start countdown. */
  startedAt?: number;
  /** Raw stage time in ms, set when finished. */
  rawMs?: number;
  penalties: Penalty[];
  /** Sum of penalties in ms. */
  penaltyMs: number;
  /** Team the driver races for; absent for independent drivers. */
  team?: string;
  teamName?: string;
  /** Car the driver runs, taken from the team when staged. */
  car?: string;
  /** Driver number. */
  number?: string;
  /** Staged from registration; follows the registration cut while still queued. */
  reg?: boolean;
  /** Quali: one lap, then stop. Long run: several laps counted with Lap, the best lap is the time. */
  mode?: "quali" | "long";
  /** Long run: lap durations in ms, in order. */
  laps?: number[];
  /** Long run: server time of the last lap mark. */
  lapAt?: number;
}

export interface Rule {
  id: string;
  name: string;
  seconds: number;
}

export interface RadioMsg {
  id: string;
  at: number;
  /**
   * "all"; "team" (to the team's channel, see `team`); "stewards" (from a team, see `team`);
   * or the ids of the runs addressed.
   */
  to: "all" | "team" | "stewards" | string[];
  team?: string;
  teamName?: string;
  text: string;
  /** What is spoken when it differs from the text (times, positions). */
  say?: string;
  from: string;
  /** A question to a driver: the driver answers with one of the options (Yes and No when `yesNo`). */
  ask?: { options: string[]; yesNo: boolean; answered?: { index: number; at: number } };
  /** Generated by race control events rather than typed by a person. */
  auto?: boolean;
  /** Colour of the line in the radio lists. */
  tone?: Tone;
}

export type Tone = "green" | "yellow" | "red" | "magenta" | "teal";

/** A steward's private note about a driver, kept by name so it follows them across runs. */
export interface DriverNote {
  id: string;
  at: number;
  by: string;
  driver: string;
  text: string;
  /** Written by a team about its own driver. Only that team and the stewards see it. */
  team?: string;
  teamName?: string;
}

export interface LogEntry {
  at: number;
  actor: string;
  text: string;
  /** Colour of the line in the steward log. */
  tone?: Tone;
}

/** A pit stop window a team plans, in milliseconds from the session start. */
export interface PitWindow {
  id: string;
  team: string;
  teamName: string;
  fromMs: number;
  toMs: number;
}

export interface RaceState {
  flag: Flag;
  runs: Run[];
  rules: Rule[];
  /** Seconds between releases. */
  cadenceSec: number;
  lastReleaseAt?: number;
  /** Finish-line timestamps not yet attributed to a car. */
  pending: number[];
  /** Team that gave up a pending finish (by timestamp), so only it can attribute that time. */
  pendingTeam?: Record<string, string>;
  radio: RadioMsg[];
  /** Staff only: stripped from every other view. */
  log: LogEntry[];
  /** Staff only. */
  notes: DriverNote[];
  /** Visible to staff and to the team they belong to. */
  pitWindows: PitWindow[];
}

export const COUNTDOWN_MS = 3000;

export const DEFAULT_RULES: Rule[] = [
  { id: "track-limit", name: "Track limit", seconds: 5 },
  { id: "jump-start", name: "Jump start", seconds: 10 },
  { id: "unsafe-reentry", name: "Unsafe re-entry", seconds: 15 },
  { id: "missed-checkpoint", name: "Missed checkpoint", seconds: 30 },
];

export const emptyState = (): RaceState => ({
  flag: "green",
  runs: [],
  rules: structuredClone(DEFAULT_RULES),
  cadenceSec: 30,
  pending: [],
  radio: [],
  log: [],
  notes: [],
  pitWindows: [],
});

export interface Viewer {
  staff: boolean;
  /** Lower-case Roblox username of a signed-in viewer. */
  user?: string;
  /** Team ids the viewer has team panel access to. */
  teams: string[];
}

/**
 * What one viewer may see. Staff see everything. Everyone else gets no audit log, and radio only
 * when signed in: messages to all, to their own runs, and their own teams' channel.
 */
export function viewFor(s: RaceState, v: Viewer): RaceState {
  if (v.staff) return s;
  const base: RaceState = { ...s, log: [], notes: s.notes.filter((n) => !!n.team && v.teams.includes(n.team)), radio: [], pitWindows: s.pitWindows.filter((w) => v.teams.includes(w.team)) };
  // Not signed in: the Public radio, which only carries Global messages.
  if (!v.user) return { ...base, radio: s.radio.filter((m) => m.to === "all") };
  const mine = s.runs.filter((r) => r.name.toLowerCase() === v.user);
  const teamOf = (runId: string) => s.runs.find((r) => r.id === runId)?.team;
  base.radio = s.radio.filter((m) => {
    if (m.to === "all") return true;
    if (m.to === "team") return !!m.team && (v.teams.includes(m.team) || mine.some((r) => r.team === m.team));
    if (m.to === "stewards") return !!m.team && v.teams.includes(m.team);
    // Addressed to drivers: the driver, and the panel of the team they race for.
    return m.to.some((id) => mine.some((r) => r.id === id) || v.teams.includes(teamOf(id) ?? ""));
  });
  return base;
}

export const publicView = (s: RaceState): RaceState => viewFor(s, { staff: false, teams: [] });

export interface Row extends Run {
  /** 1-based rank, only for finished runs. */
  rank?: number;
  finalMs?: number;
}

const ORDER: Record<RunStatus, number> = { finished: 0, onstage: 1, queued: 2, dnf: 3 };

/** Finished runs ranked by fastest final time, then on stage, queued, DNF in entry order. */
export function classify(runs: Run[]): Row[] {
  const all: Row[] = runs.map((r) => ({
    ...r,
    finalMs: r.status === "finished" && r.rawMs != null ? r.rawMs + r.penaltyMs : undefined,
  }));

  const byDriver = new Map<string, Row[]>();
  for (const r of all) {
    const key = r.name.toLowerCase();
    const list = byDriver.get(key) ?? [];
    list.push(r);
    byDriver.set(key, list);
  }

  const selected: Row[] = [];
  for (const list of byDriver.values()) {
    // Best finished run (fastest finalMs)
    const finished = list.filter((r) => r.status === "finished" && r.finalMs != null);
    if (finished.length > 0) {
      finished.sort((a, b) => a.finalMs! - b.finalMs!);
      selected.push(finished[0]);
    } else {
      // If no finished runs, keep the latest DNF run if any
      const dnfs = list.filter((r) => r.status === "dnf");
      if (dnfs.length > 0) {
        selected.push(dnfs[dnfs.length - 1]);
      }
    }

    // Active runs (queued or onstage)
    const active = list.filter((r) => r.status === "queued" || r.status === "onstage");
    for (const a of active) {
      selected.push(a);
    }
  }

  const entryIndex = new Map(all.map((r, i) => [r.id, i]));
  selected.sort((a, b) => {
    if (ORDER[a.status] !== ORDER[b.status]) return ORDER[a.status] - ORDER[b.status];
    if (a.status === "finished" && a.finalMs != null && b.finalMs != null) {
      return a.finalMs - b.finalMs;
    }
    return (entryIndex.get(a.id) ?? 0) - (entryIndex.get(b.id) ?? 0);
  });

  let rank = 0;
  for (const r of selected) if (r.status === "finished" && r.finalMs != null) r.rank = ++rank;
  return selected;
}

/** mm:ss.mmm */
export function fmtTime(ms: number): string {
  const m = Math.floor(ms / 60000);
  const s = Math.floor((ms % 60000) / 1000);
  const t = Math.floor(ms % 1000);
  return `${String(m).padStart(2, "0")}:${String(s).padStart(2, "0")}.${String(t).padStart(3, "0")}`;
}

/** +5.000 */
export function fmtPenalty(ms: number): string {
  return `+${(ms / 1000).toFixed(3)}`;
}

/** "1 minute 23.4 seconds", for speech. */
export function spokenTime(ms: number) {
  const m = Math.floor(ms / 60000);
  const sec = ((ms % 60000) / 1000).toFixed(1);
  return `${m ? `${m} minute${m > 1 ? "s" : ""} ` : ""}${sec} seconds`;
}
